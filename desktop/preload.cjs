const {contextBridge, ipcRenderer} = require('electron');

contextBridge.exposeInMainWorld('apollo', {
  close: () => ipcRenderer.invoke('window:close'),
  minimize: () => ipcRenderer.invoke('window:minimize'),
  maximize: () => ipcRenderer.invoke('window:maximize'),
  getInfo: () => ipcRenderer.invoke('app:info'),
  updates: {state:()=>ipcRenderer.invoke('update:state'),check:()=>ipcRenderer.invoke('update:check'),download:()=>ipcRenderer.invoke('update:download'),install:()=>ipcRenderer.invoke('update:install')},
  getConfig: () => ipcRenderer.invoke('config:get'),
  getModels: (config) => ipcRenderer.invoke('connection:models', config),
  testConnection: (config) => ipcRenderer.invoke('connection:test', config),
  saveConfig: (config) => ipcRenderer.invoke('config:save', config),
  chat: (payload) => ipcRenderer.invoke('chat:send', payload),
  getProject: () => ipcRenderer.invoke('project:get'),
  chooseProject: () => ipcRenderer.invoke('project:choose'),
  listFiles: (relative) => ipcRenderer.invoke('project:files', relative),
  readFile: (relative) => ipcRenderer.invoke('project:read', relative),
  gitStatus: () => ipcRenderer.invoke('git:status'),
  gitDiff: () => ipcRenderer.invoke('git:diff'),
  applyPatch: (patch) => ipcRenderer.invoke('patch:apply', patch),
  runTests: () => ipcRenderer.invoke('test:run'),
  listSkills: () => ipcRenderer.invoke('skills:list'),
  workflows: {
    state:()=>ipcRenderer.invoke('workflow:state'),
    create:input=>ipcRenderer.invoke('workflow:create',input),
    saveTemplate:input=>ipcRenderer.invoke('workflow:template',input),
    advance:(id,approved)=>ipcRenderer.invoke('workflow:advance',id,approved),
    cancel:()=>ipcRenderer.invoke('workflow:cancel'),
  },
  browser: {
    open:url=>ipcRenderer.invoke('browser:open',url),
    snapshot:()=>ipcRenderer.invoke('browser:snapshot'),
    action:(kind,id,text)=>ipcRenderer.invoke('browser:action',kind,id,text),
    preview:()=>ipcRenderer.invoke('browser:preview'),
    show:()=>ipcRenderer.invoke('browser:show'),
    close:()=>ipcRenderer.invoke('browser:close'),
  },
  computer: {
    windows:()=>ipcRenderer.invoke('computer:windows'),
    select:(handle,pid)=>ipcRenderer.invoke('computer:select',handle,pid),
    snapshot:()=>ipcRenderer.invoke('computer:snapshot'),
    action:(kind,id,text)=>ipcRenderer.invoke('computer:action',kind,id,text),
    revoke:()=>ipcRenderer.invoke('computer:revoke'),
  },
  runtime: {
    state: () => ipcRenderer.invoke('runtime:state'),
    saveSettings: (settings) => ipcRenderer.invoke('runtime:settings', settings),
    saveSkill: (skill) => ipcRenderer.invoke('runtime:skill:save', skill),
    readSkill: (id) => ipcRenderer.invoke('runtime:skill:read', id),
    importSkill: () => ipcRenderer.invoke('runtime:skill:import'),
    saveMcp: (server) => ipcRenderer.invoke('runtime:mcp:save', server),
    connectMcp: (id) => ipcRenderer.invoke('runtime:mcp:connect', id),
    disconnectMcp: (id) => ipcRenderer.invoke('runtime:mcp:disconnect', id),
    saveMemory: (text) => ipcRenderer.invoke('runtime:memory', text),
    cancel: () => ipcRenderer.invoke('runtime:cancel'),
    rollback: (id) => ipcRenderer.invoke('runtime:rollback', id),
    switchProvider: (id) => ipcRenderer.invoke('runtime:provider', id),
    onEvent: (callback) => {const handler=(_,event)=>callback(event);ipcRenderer.on('runtime:event',handler);return ()=>ipcRenderer.removeListener('runtime:event',handler);},
  },
});
